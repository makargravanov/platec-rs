pub fn scaled_octave_noise_4d(
    octaves: f32,
    persistence: f32,
    scale: f32,
    low: f32,
    high: f32,
    x: f32,
    y: f32,
    z: f32,
    w: f32,
) -> f32 {
    let mut total = 0.0;
    let mut frequency = scale;
    let mut amplitude = 1.0;
    let mut max_amplitude = 0.0;
    let mut octave = 0.0;

    while octave < octaves {
        total +=
            raw_noise_4d(x * frequency, y * frequency, z * frequency, w * frequency) * amplitude;
        frequency *= 2.0;
        max_amplitude += amplitude;
        amplitude *= persistence;
        octave += 1.0;
    }

    let normalized = total / max_amplitude;
    normalized * (high - low) / 2.0 + (high + low) / 2.0
}

fn raw_noise_4d(x: f32, y: f32, z: f32, w: f32) -> f32 {
    const F4: f32 = 0.309_016_994;
    const G4: f32 = 0.138_196_601;

    let s = (x + y + z + w) * F4;
    let i = fastfloor(x + s);
    let j = fastfloor(y + s);
    let k = fastfloor(z + s);
    let l = fastfloor(w + s);
    let t = (i + j + k + l) as f32 * G4;
    let x0 = x - (i as f32 - t);
    let y0 = y - (j as f32 - t);
    let z0 = z - (k as f32 - t);
    let w0 = w - (l as f32 - t);

    let c1 = (x0 > y0) as usize;
    let c2 = (x0 > z0) as usize;
    let c3 = (y0 > z0) as usize;
    let c4 = (x0 > w0) as usize;
    let c5 = (y0 > w0) as usize;
    let c6 = (z0 > w0) as usize;
    let c = (c1 << 5) | (c2 << 4) | (c3 << 3) | (c4 << 2) | (c5 << 1) | c6;
    let rank = SIMPLEX[c];

    let i1 = (rank[0] >= 3) as i32;
    let j1 = (rank[1] >= 3) as i32;
    let k1 = (rank[2] >= 3) as i32;
    let l1 = (rank[3] >= 3) as i32;
    let i2 = (rank[0] >= 2) as i32;
    let j2 = (rank[1] >= 2) as i32;
    let k2 = (rank[2] >= 2) as i32;
    let l2 = (rank[3] >= 2) as i32;
    let i3 = (rank[0] >= 1) as i32;
    let j3 = (rank[1] >= 1) as i32;
    let k3 = (rank[2] >= 1) as i32;
    let l3 = (rank[3] >= 1) as i32;

    let x1 = x0 - i1 as f32 + G4;
    let y1 = y0 - j1 as f32 + G4;
    let z1 = z0 - k1 as f32 + G4;
    let w1 = w0 - l1 as f32 + G4;
    let x2 = x0 - i2 as f32 + 2.0 * G4;
    let y2 = y0 - j2 as f32 + 2.0 * G4;
    let z2 = z0 - k2 as f32 + 2.0 * G4;
    let w2 = w0 - l2 as f32 + 2.0 * G4;
    let x3 = x0 - i3 as f32 + 3.0 * G4;
    let y3 = y0 - j3 as f32 + 3.0 * G4;
    let z3 = z0 - k3 as f32 + 3.0 * G4;
    let w3 = w0 - l3 as f32 + 3.0 * G4;
    let x4 = x0 - 1.0 + 4.0 * G4;
    let y4 = y0 - 1.0 + 4.0 * G4;
    let z4 = z0 - 1.0 + 4.0 * G4;
    let w4 = w0 - 1.0 + 4.0 * G4;

    let ii = (i & 255) as usize;
    let jj = (j & 255) as usize;
    let kk = (k & 255) as usize;
    let ll = (l & 255) as usize;

    let gi0 = PERM[ii + PERM[jj + PERM[kk + PERM[ll]]]] % 32;
    let gi1 = PERM[ii
        + i1 as usize
        + PERM[jj + j1 as usize + PERM[kk + k1 as usize + PERM[ll + l1 as usize]]]]
        % 32;
    let gi2 = PERM[ii
        + i2 as usize
        + PERM[jj + j2 as usize + PERM[kk + k2 as usize + PERM[ll + l2 as usize]]]]
        % 32;
    let gi3 = PERM[ii
        + i3 as usize
        + PERM[jj + j3 as usize + PERM[kk + k3 as usize + PERM[ll + l3 as usize]]]]
        % 32;
    let gi4 = PERM[ii + 1 + PERM[jj + 1 + PERM[kk + 1 + PERM[ll + 1]]]] % 32;

    27.0 * (corner(gi0, x0, y0, z0, w0)
        + corner(gi1, x1, y1, z1, w1)
        + corner(gi2, x2, y2, z2, w2)
        + corner(gi3, x3, y3, z3, w3)
        + corner(gi4, x4, y4, z4, w4))
}

#[inline]
fn corner(grad: usize, x: f32, y: f32, z: f32, w: f32) -> f32 {
    let mut t = 0.6 - x * x - y * y - z * z - w * w;
    if t < 0.0 {
        0.0
    } else {
        t *= t;
        t * t * dot4(&GRAD4[grad], x, y, z, w)
    }
}

#[inline]
fn fastfloor(x: f32) -> i32 {
    if x > 0.0 { x as i32 } else { x as i32 - 1 }
}

#[inline]
fn dot4(g: &[i32; 4], x: f32, y: f32, z: f32, w: f32) -> f32 {
    g[0] as f32 * x + g[1] as f32 * y + g[2] as f32 * z + g[3] as f32 * w
}
